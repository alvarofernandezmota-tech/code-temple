CHAR_W = 4      # 3 px de glifo + 1 de separacion
CHAR_H = 6


def text_width(s):
    return len(s) * CHAR_W - 1


def draw(surf, s, pos, color, spacing=CHAR_W):
    x, y = pos
    for ch in s.upper():
        glyph = GLYPHS.get(ch)
        if glyph:
            for gy, row in enumerate(glyph):
                for gx, c in enumerate(row):
                    if c == "#":
                        surf.set_at((x + gx, y + gy), color)
        x += spacing


def draw_centered(surf, s, center_x, y, color):
    draw(surf, s, (center_x - text_width(s) // 2, y), color)
